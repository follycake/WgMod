[Credit(ProjectRole.Programmer, Contributor.maimaichubs)]
[Credit(ProjectRole.Artist, Contributor.PLACEHOLDER)]
public class SolDrive : ModItem
{
    WgStat _damage = new(0.16f, 0.32f);
    WgStat _attackSpeed = new(0.08f, 0.16f);
    WgStat _critChance = new(5f, 10f);
    WgStat _armorPenetration = new(2f, 6f);
    WgStat _meleeSize = new(0f, 0.1f);

    public override void SetDefaults()
    {
        Item.width = 26;
        Item.height = 30;

        Item.accessory = true;
        Item.rare = ItemRarityID.Yellow;
        Item.value = Item.buyPrice(gold: 14);
    }

    public static readonly DamageClass[] Melee = [
        DamageClass.Melee,
        DamageClass.MeleeNoSpeed,
    ];

    public override void UpdateAccessory(Player player, bool hideVisual)
    {
        if (!player.TryGetModPlayer(out WgPlayer wg) || !player.TryGetModPlayer(out SolDrivePlayer sd) || !player.TryGetModPlayer(out QueenlyGluttonyPlayer qg))
            return;

        float immobility = wg.Weight.ClampedImmobility;

        if (!qg._active)
        {
            _damage.Lerp(immobility);
            _attackSpeed.Lerp(immobility);
            _critChance.Lerp(immobility);
            _armorPenetration.Lerp(immobility);
            _meleeSize.Lerp(immobility);


            foreach (var item in Melee)
            {
                player.GetDamage(item) += _damage;
                player.GetAttackSpeed(item) -= _attackSpeed;
                player.GetCritChance(item) += _critChance;
                player.GetArmorPenetration(item) += _armorPenetration;
            }

            player.meleeScaleGlove = true;
            player.autoReuseGlove = true;
            player.kbGlove = true;
            player.magmaStone = true;

            sd._active = true;
            sd._meleeSize = _meleeSize;
        }
    }

    public override void ModifyTooltips(List<TooltipLine> tooltips)
    {
        Player player = Main.LocalPlayer;

        if (!player.TryGetModPlayer(out QueenlyGluttonyPlayer qg))
            return;

        tooltips.FormatLines(_damage.Percent(), _attackSpeed.Percent(), _critChance, _armorPenetration, (_meleeSize + 0.1f).Percent());

        if (qg._active)
        {
            tooltips.LineBeforeTooltip(out TooltipLine line);
            tooltips.Insert(tooltips.IndexOf(line) + 1, new TooltipLine(Mod, "NewTooltip", Language.GetTextValue("Mods.WgMod.GlobalItem.Disabled", ModContent.GetInstance<QueenlyGluttony>().DisplayName)));
        }
    }

    public override void AddRecipes()
    {
        CreateRecipe()
            .AddIngredient(ItemID.FireGauntlet)
            .AddIngredient(ModContent.ItemType<QueenlyGluttony>())
            .AddIngredient(ItemID.LunarTabletFragment, 12)
            .AddTile(TileID.MythrilAnvil)
            .Register();
    }
}

public class SolDrivePlayer : ModPlayer
{
    public bool _active;

    public int _dust = DustID.SolarFlare;

    public WgStat _meleeSize;

    public override void ResetEffects()
    {
        _active = false;
    }

    public static readonly DamageClass[] Melee = [
        DamageClass.Melee,
        DamageClass.MeleeNoSpeed,
    ];

    static readonly WeightedRandom<int> _buffs = new();

    public override void SetStaticDefaults()
    {
        _buffs.Add(BuffID.Oiled, 25);
        _buffs.Add(BuffID.OnFire, 50);
        _buffs.Add(BuffID.Frostburn, 25);
        _buffs.Add(BuffID.Frostburn2, 10);
        _buffs.Add(BuffID.CursedInferno, 5);
        _buffs.Add(BuffID.ShadowFlame, 1);
        _buffs.Add(BuffID.GelBalloonBuff, 50);
        _buffs.Add(BuffID.Slimed, 25);
        _buffs.Add(BuffID.Stinky, 10);
        _buffs.Add(BuffID.Shimmer, 1);
    }

    public override void OnHitNPC(NPC target, NPC.HitInfo hit, int damageDone)
    {
        if (!Player.TryGetModPlayer(out WgPlayer wg) || !_active || !Melee.Contains(hit.DamageType))
            return;
        float immobility = wg.Weight.ClampedImmobility;

        int duration = (int)((1f + immobility) * 3f);

        target.AddBuff(_buffs, duration * 60);
    }

    public override void ModifyItemScale(Item item, ref float scale)
    {
        if (!_active || !Melee.Contains(item.DamageType) || Player.TryGetModPlayer(out ChampionsBeltPlayer cb) || cb._active)
            return;

        scale += _meleeSize;
    }

    public override void MeleeEffects(Item item, Rectangle hitbox)
    {
        if (!_active || !Melee.Contains(item.DamageType))
            return;

        if (Main.rand.NextBool(3))
        {
            int dust = Dust.NewDust(hitbox.TopLeft(), hitbox.Width, hitbox.Height, _dust, 0f, 0f, 100, default, 1f);
            Main.dust[dust].noGravity = true;
        }
    }

    public override void EmitEnchantmentVisualsAt(Projectile projectile, Vector2 boxPosition, int boxWidth, int boxHeight)
    {
        if (!_active || !Melee.Contains(projectile.DamageType))
            return;

        if (Main.rand.NextBool(3))
        {
            int dust = Dust.NewDust(boxPosition, boxWidth, boxHeight, _dust, 0f, 0f, 100, default, 1f);
            Main.dust[dust].noGravity = true;
        }
    }
}

