namespace WgMod.Content.Items.Accessories.Melee;

[Credit(ProjectRole.Programmer, Contributor.maimaichubs)]
[Credit(ProjectRole.Artist, Contributor.trilophyte)]
public class QueenlyGluttony : ModItem
{
    WgStat _damage = new(0.05f, 0.2f);
    WgStat _attackSpeed = new(0.04f, 0.16f);
    WgStat _critChance = new(5f, 10f);
    WgStat _armorPenetration = new(2f, 6f);

    public override void SetDefaults()
    {
        Item.width = 28;
        Item.height = 30;

        Item.accessory = true;
        Item.rare = ItemRarityID.Pink;
        Item.value = Item.buyPrice(gold: 4);
    }

    public override void UpdateAccessory(Player player, bool hideVisual)
    {
        if (!player.TryGetModPlayer(out WgPlayer wg) || !player.TryGetModPlayer(out QueenlyGluttonyPlayer qg))
            return;
        float immobility = wg.Weight.ClampedImmobility;

        _damage.Lerp(immobility);
        _attackSpeed.Lerp(immobility);
        _critChance.Lerp(immobility);
        _armorPenetration.Lerp(immobility);

        player.GetDamage(DamageClass.Melee) += _damage;
        player.GetAttackSpeed(DamageClass.Melee) -= _attackSpeed;
        player.GetCritChance(DamageClass.Melee) += _critChance;
        player.GetArmorPenetration(DamageClass.Melee) += _armorPenetration;

        qg.active = true;
    }

    public override void ModifyResearchSorting(ref ContentSamples.CreativeHelper.ItemGroup itemGroup)
    {
        itemGroup = ContentSamples.CreativeHelper.ItemGroup.Accessories;
    }

    public override void ModifyTooltips(List<TooltipLine> tooltips)
    {
        tooltips.FormatLines(_damage.Percent(), _attackSpeed.Percent(), _critChance, _armorPenetration);
    }
}

public class QueenlyGluttonyPlayer : ModPlayer
{
    public bool active;

    public int _dust = DustID.PinkSlime;

    public override void ResetEffects()
    {
        active = false;
    }

    public static readonly DamageClass[] Melee =
    [
        DamageClass.Melee,
        DamageClass.MeleeNoSpeed
    ];

    public override void OnHitNPC(NPC target, NPC.HitInfo hit, int damageDone)
    {
        if (!active || !Melee.Contains(hit.DamageType))
            return;

        if (Main.rand.NextBool(50))
            target.AddBuff(BuffID.Shimmer, 2 * 60);
        else
            target.AddBuff(BuffID.GelBalloonBuff, 2 * 60);
    }

    public override void MeleeEffects(Item item, Rectangle hitbox)
    {
        if (!active || !Melee.Contains(item.DamageType))
            return;

        if (Main.rand.NextBool(3))
        {
            int dust = Dust.NewDust(hitbox.TopLeft(), hitbox.Width, hitbox.Height, _dust, 0f, 0f, 100, default, 1f);
            Main.dust[dust].noGravity = true;
        }
    }

    public override void EmitEnchantmentVisualsAt(Projectile projectile, Vector2 boxPosition, int boxWidth, int boxHeight)
    {
        if (!active || !Melee.Contains(projectile.DamageType))
            return;

        if (Main.rand.NextBool(3))
        {
            int dust = Dust.NewDust(boxPosition, boxWidth, boxHeight, _dust, 0f, 0f, 100, default, 1f);
            Main.dust[dust].noGravity = true;
        }
    }
}

